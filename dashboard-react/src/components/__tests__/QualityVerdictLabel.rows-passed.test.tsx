/**
 * The DQ report still renders after p37 widened its type (task 6.6, R4.5).
 *
 * **Validates: Requirements 4.5**
 *
 * R4 **reclassifies** the DQ_Report_Row — it stops `execution_updater` writing a
 * `steps_status` entry for a row that is not a pipeline step — and it does not
 * suppress the row. `use-quality-report.ts` and `QualityVerdictLabel` read that
 * row by its own key and its own producer stamp, and `LGR-99050e6-2`
 * (**template / ratified**) is the record for why the stamp rather than the
 * pipeline config is the per-run truth. Nothing in Requirement 4 touches that
 * read.
 *
 * p37 task 6.5 nonetheless **edited `use-quality-report.ts`**, adding
 * `rows_passed?: number` to `QualityReport` so `LoadOutcomeLabel` could
 * corroborate its counts. `QualityVerdictLabel` and `QualityReportCard` both
 * read that interface. This file is the permanent assertion that the edit
 * changed nothing for them:
 *
 * - `deriveQualityVerdict` returns a **deep-equal** verdict with and without
 *   `rows_passed` on the row, for every producer state. That is the strong form
 *   of "it never reads it": it holds without needing to inspect the function.
 * - `QualityVerdictLabel` still renders its verdict **and its evidence**,
 *   including the quarantine prefix.
 * - `QualityReportCard` still renders the report — the card, the overall status,
 *   every check, the recommendations and the root cause — and still contains the
 *   verdict label.
 * - The new `LoadOutcomeLabel` is a **sibling**, so it is absent from these
 *   surfaces entirely: no branch was added to `QualityVerdictLabel` and nothing
 *   was merged into it.
 *
 * The existing `QualityVerdictLabel.test.tsx` already carried `rows_passed` in
 * its transcribed state rows, but as an undeclared extra key tolerated by an
 * index signature. Here it is asserted as a **declared field** of
 * `QualityReport`, which is what task 6.5 actually changed.
 *
 * Fixtures are literal state rows from the two producers
 * (`pyspark_templates/glue_job_s3_tables.py.j2`,
 * `agentcore/data_quality_agent/main.py`) rather than produced by calling either
 * one — a fixture derived from the producer cannot detect the producer drifting
 * (`LGR-28b4d75-5`).
 */
import { describe, it, expect, vi } from 'vitest';
import { render, screen } from '@testing-library/react';
import QualityVerdictLabel, { deriveQualityVerdict } from '../QualityVerdictLabel';
import QualityReportCard from '../QualityReportCard';
import DataQualityTab from '../run-detail/DataQualityTab';
import type { QualityReport } from '../../hooks/use-quality-report';

type StateRow = QualityReport & Record<string, unknown>;

/** Inline producer, failing rows quarantined — carries `rows_passed`. */
const INLINE_QUARANTINED: StateRow = {
  pipeline_id: 'pipe-1',
  run_id: 'run-1',
  step_name: 'data_quality',
  overall_status: 'fail',
  checks: [
    { name: 'Completeness "phone" >= 0.95', status: 'fail', actual: 0 },
    { name: 'RowCount > 0', status: 'pass', actual: 5 },
  ],
  root_cause: 'data_issue',
  recommendations: ['Review failed data quality rules'],
  source: 'glue_inline_dq',
  timestamp: '2026-08-09T15:38:19+00:00',
  rules_passed: 10,
  rules_failed: 1,
  rules_total: 11,
  rows_passed: 0,
  rows_quarantined: 5,
  quarantine_path: 's3://adi-quarantine/quarantine/run-1/',
};

/** Inline producer, everything passed. */
const INLINE_ALL_PASSED: StateRow = {
  ...INLINE_QUARANTINED,
  overall_status: 'pass',
  checks: [{ name: 'RowCount > 0', status: 'pass', actual: 1200 }],
  root_cause: null,
  recommendations: [],
  rules_failed: 0,
  rows_passed: 1200,
  rows_quarantined: 0,
  quarantine_path: null,
};

/** Inline producer, dataset-level rule failed with nothing withheld. */
const INLINE_DATASET_RULE_FAILED: StateRow = {
  ...INLINE_ALL_PASSED,
  overall_status: 'fail',
  checks: [{ name: 'RowCount > 0', status: 'fail', actual: 0 }],
  root_cause: 'data_issue',
  rules_failed: 1,
  rows_passed: 0,
};

/** On-demand agent row. Does not write `rows_passed` at all. */
const AGENT_REPORT: StateRow = {
  pipeline_id: 'pipe-1',
  run_id: 'run-1',
  step_name: 'data_quality',
  agent_type: 'data_quality',
  overall_status: 'pass',
  checks: [{ name: 'row_count', status: 'pass', actual: 1200 }],
  root_cause: null,
  recommendations: [],
  timestamp: '2026-08-09T16:00:00+00:00',
};

/**
 * Blank out React's `useId` values before comparing markup.
 *
 * Cloudscape's `Alert` wires its header to its body with a `useId`, which
 * increments once per mount for the lifetime of the module — so two sequential
 * renders of the *same* component differ in that attribute regardless of what is
 * being compared. It is generated by React from a render counter and cannot
 * carry information about the report, so blanking it is what makes the
 * comparison a statement about `rows_passed` rather than about render order.
 */
function normaliseGeneratedIds(html: string): string {
  return html.replace(/:r[0-9a-z]+:/g, ':generated-id:');
}

describe('deriveQualityVerdict is unchanged by rows_passed (R4.5)', () => {
  it.each([
    ['a quarantined inline report', INLINE_QUARANTINED],
    ['an all-passed inline report', INLINE_ALL_PASSED],
    ['a dataset-level inline failure', INLINE_DATASET_RULE_FAILED],
  ])('returns the same verdict for %s with and without the field', (_label, row) => {
    const { rows_passed: _dropped, ...withoutField } = row;

    expect(deriveQualityVerdict(row)).toEqual(deriveQualityVerdict(withoutField as StateRow));
  });

  it('is unaffected by the value of rows_passed, including a nonsensical one', () => {
    const baseline = deriveQualityVerdict(INLINE_QUARANTINED);

    for (const rows_passed of [0, 1, 999_999, -1, Number.NaN]) {
      expect(deriveQualityVerdict({ ...INLINE_QUARANTINED, rows_passed })).toEqual(baseline);
    }
  });

  it('still reads the quarantine counter and path it has always read', () => {
    // The fields R4.5 protects are the ones the verdict is actually derived
    // from. `rows_passed` sitting beside them must not displace them.
    const verdict = deriveQualityVerdict(INLINE_QUARANTINED);

    expect(verdict.mode).toBe('enforced_row_level');
    expect(verdict.heading).toMatch(/quarantined before load/i);
    expect(verdict.detail).toContain('5');
    expect(verdict.evidence).toContain('s3://adi-quarantine/quarantine/run-1/');
    expect(verdict.alertType).toBe('info');
  });

  it('still treats an absent quarantine counter as unknown, with rows_passed present', () => {
    // `LGR-99050e6-2` (template / ratified). Adding a sibling counter must not
    // make an absent one read as zero.
    const { rows_quarantined: _dropped, ...withoutCounter } = INLINE_QUARANTINED;
    const verdict = deriveQualityVerdict(withoutCounter as StateRow);

    expect(verdict.heading).toMatch(/not recorded/i);
    expect(verdict.detail).toMatch(/cannot be determined/i);
    expect(verdict.alertType).toBe('warning');
  });

  it('still classifies the agent report by its own stamp', () => {
    const verdict = deriveQualityVerdict(AGENT_REPORT);

    expect(verdict.mode).toBe('advisory');
    expect(verdict.heading).toMatch(/reported after load/i);
  });
});

describe('QualityVerdictLabel still renders its verdict and evidence (R4.5)', () => {
  it('renders the label with rows_passed present on the report', () => {
    render(<QualityVerdictLabel report={INLINE_QUARANTINED} />);

    const label = screen.getByTestId('quality-verdict-label');
    expect(label).toBeInTheDocument();
    expect(label.textContent).toMatch(/quarantined before load/i);
  });

  it('renders the quarantine prefix as evidence with rows_passed present', () => {
    render(<QualityVerdictLabel report={INLINE_QUARANTINED} />);

    expect(screen.getByTestId('quality-verdict-evidence').textContent).toContain(
      's3://adi-quarantine/quarantine/run-1/',
    );
  });

  it('renders identical markup with and without the field', () => {
    const { rows_passed: _dropped, ...withoutField } = INLINE_QUARANTINED;

    const withField = render(<QualityVerdictLabel report={INLINE_QUARANTINED} />);
    const html = normaliseGeneratedIds(withField.container.innerHTML);
    withField.unmount();

    const without = render(<QualityVerdictLabel report={withoutField as StateRow} />);
    expect(normaliseGeneratedIds(without.container.innerHTML)).toBe(html);
  });
});

describe('QualityReportCard still renders the report (R4.5)', () => {
  it('renders the card, the overall status and every check with rows_passed present', () => {
    render(<QualityReportCard report={INLINE_QUARANTINED} />);

    expect(screen.getByTestId('quality-report-card')).toBeInTheDocument();
    expect(screen.getByText(/Overall: FAIL/)).toBeInTheDocument();
    for (const check of INLINE_QUARANTINED.checks) {
      expect(screen.getByTestId(`quality-check-${check.name}`)).toBeInTheDocument();
    }
  });

  it('still renders the recommendations and the root cause', () => {
    render(<QualityReportCard report={INLINE_QUARANTINED} />);

    expect(screen.getByText('Review failed data quality rules', { exact: false })).toBeInTheDocument();
    expect(screen.getByText('data_issue')).toBeInTheDocument();
  });

  it('still contains the verdict label, above the overall status', () => {
    render(<QualityReportCard report={INLINE_QUARANTINED} />);

    const card = screen.getByTestId('quality-report-card');
    const label = screen.getByTestId('quality-verdict-label');
    expect(card).toContainElement(label);
    // Node.DOCUMENT_POSITION_FOLLOWING === 4
    expect(label.compareDocumentPosition(screen.getByText(/Overall: FAIL/)) & 4).toBeTruthy();
  });

  it('reaches the Data Quality tab unchanged', () => {
    render(<DataQualityTab qualityReport={INLINE_QUARANTINED} onRetry={vi.fn()} />);

    expect(screen.getByTestId('quality-report-card')).toContainElement(
      screen.getByTestId('quality-verdict-label'),
    );
  });

  it('does not put the load label on the quality surface — it is a sibling, not a branch', () => {
    // `LoadOutcomeLabel` is mounted above the tabs by `RunDetailPage`, not
    // inside `QualityReportCard`. Nothing was merged into the quality label.
    render(<DataQualityTab qualityReport={INLINE_QUARANTINED} onRetry={vi.fn()} />);

    expect(screen.queryByTestId('load-outcome-label')).not.toBeInTheDocument();
    expect(screen.queryByTestId('load-outcome-counts')).not.toBeInTheDocument();
  });
});
