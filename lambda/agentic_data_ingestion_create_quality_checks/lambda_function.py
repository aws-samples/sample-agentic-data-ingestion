def get_target_schema_for_quality_checks(mapping_id: str) -> dict:
    """Get target schema from mapping for quality check generation.

    Not-found returns {} so downstream rule generation degrades to no-rules
    (P21 Req 6.4). Infrastructure errors (throttles, access denied) raise
    instead of masquerading as a missing schema (P28 R17.3).
    """
    if not mapping_id:
        logger.warning("No mapping_id provided for quality checks")
        return {}
    try:
        response = mappings_table.get_item(Key={"mapping_id": mapping_id})
    except ClientError as e:
        raise_for_read_client_error(e, "create_quality_checks", operation="get_target_schema_for_quality_checks")
        logger.error(f"Mappings table not found getting target schema for {mapping_id}: {e}")
        return {}
    if "Item" in response:
        target_schema: dict = response["Item"].get("target_schema", {})
        return target_schema
    return {}


def get_code_generation_facts(run_id: str) -> dict:
    """Read the two facts the Quality_Verdict mode is derived from (p30 R7.2).

    Both live on this run's ``create_code`` state row, which is written at step
    5 — long before this step (13) runs:

    - ``output_data.summary.template_used`` — the PySpark template actually
      rendered, i.e. ``TEMPLATE_RULES``' own resolution of the
      (source_type, target_type) pair, or ``"fallback_full_ai_v1"`` for the
      full-AI path. This is read INSTEAD of re-deriving the pair from the
      pipeline record: re-deriving would duplicate ``TEMPLATE_RULES`` here,
      free to drift from the module that owns it, and would answer the
      fallback path wrongly.
    - ``output_data.approval.dqdl_rules`` — the exact DQDL ruleset baked into
      the generated code, generated by ``create_code`` from the approved field
      mappings. Its emptiness is R7.4's degradation, and it is NOT inferable
      from this step's own ``quality_rules`` (a different rule vocabulary).
    - ``output_data.summary.data_quality_enabled`` — p64 R6.6. THREE facts, not
      two, since R6.1 put the ``EvaluateDataQuality`` block in all five
      templates: the template name no longer answers on its own whether the job
      gates its write, because four of the five carry the block but render it
      only for a pipeline that opted in. ``create_code`` resolves this once at
      render time and records it here.

      ABSENT IS NOT ``False``. A row written before p64 has no such key, and
      reporting it as "off" would relabel every pre-p64 S3 Tables run from
      ``enforced`` to ``advisory`` — the same silent reclassification R6.6
      forbids, pointing the other way. So an absent key travels as ``None`` and
      ``derive_quality_verdict`` falls back to the default posture, which is
      what such a row actually ran. ``bool()`` on the raw value would collapse
      that distinction, which is why the read is an explicit ``is None`` test.

    Unlike :func:`get_target_schema_for_quality_checks`, a read failure here
    does NOT raise. That helper's reads feed rule generation, where silent
    degradation changed behaviour invisibly (P28 R17.3); this read feeds a
    provenance annotation, and its degradation is recorded IN the annotation
    (``determined_from``) rather than hidden — so failing the pipeline step
    over it would trade a visible caveat for an outage.
    """
    try:
        response = pipeline_runs_table.get_item(Key={"run_id": run_id, "step_name": StepName.CREATE_CODE})
    except ClientError as e:
        logger.warning(f"Could not read create_code row for {run_id} to derive the quality verdict: {e}")
        return {"determined_from": FROM_UNREADABLE_CREATE_CODE_ROW}
    if "Item" not in response:
        logger.warning(f"No create_code state row for {run_id} — quality verdict mode cannot be established")
        return {"determined_from": FROM_MISSING_CREATE_CODE_ROW}

    output_data = response["Item"].get("output_data") or {}
    summary = output_data.get("summary") or {}
    approval = output_data.get("approval") or {}
    # p64 R6.6. Only a real bool is carried through; anything else — a missing key
    # on a pre-p64 row, or a value of some other type — becomes None, meaning "not
    # established", which `derive_quality_verdict` resolves to the default posture.
    raw_enabled = summary.get("data_quality_enabled")
    return {
        "template_used": str(summary.get("template_used") or ""),
        "target_type": str(summary.get("target_type") or ""),
        # Empty string is meaningful (no rules generated), so it is preserved
        # rather than normalised away.
        "dqdl_rules": str(approval.get("dqdl_rules") or ""),
        "data_quality_enabled": raw_enabled if isinstance(raw_enabled, bool) else None,
        "determined_from": FROM_CREATE_CODE_ROW,
    }


def generate_quality_check_rules(target_schema: dict) -> list[dict]:
    """Generate data quality check rules based on target schema"""
    try:
        quality_rules = []
        properties = target_schema.get("properties", {})

        for field_name, field_info in properties.items():
            field_type = field_info.get("type", "string")

            # Generate type validation rules
            quality_rules.append(
                {
                    "rule_name": f"{field_name}_type_check",
                    "rule_type": "data_type_validation",
                    "field": field_name,
                    "expected_type": field_type,
                    "severity": "error",
                    "description": f"Validate that {field_name} is of type {field_type}",
                }
            )

            # Generate null checks for required fields
            if field_name in target_schema.get("required", []):
                quality_rules.append(
                    {
                        "rule_name": f"{field_name}_null_check",
                        "rule_type": "null_validation",
                        "field": field_name,
                        "allow_null": False,
                        "severity": "error",
                        "description": f"Validate that required field {field_name} is not null",
                    }
                )

            # Generate format validation for specific types
            if field_type == "string" and "format" in field_info:
                format_type = field_info["format"]
                quality_rules.append(
                    {
                        "rule_name": f"{field_name}_format_check",
                        "rule_type": "format_validation",
                        "field": field_name,
                        "expected_format": format_type,
                        "severity": "warning",
                        "description": f"Validate that {field_name} matches {format_type} format",
                    }
                )

            # Generate range checks for numeric fields
            if field_type in ["integer", "number"]:
                quality_rules.append(
                    {
                        "rule_name": f"{field_name}_range_check",
                        "rule_type": "range_validation",
                        "field": field_name,
                        "min_value": field_info.get("minimum", None),
                        "max_value": field_info.get("maximum", None),
                        "severity": "warning",
                        "description": f"Validate that {field_name} is within expected range",
                    }
                )

        # Add overall data quality rules
        quality_rules.extend(
            [
                {
                    "rule_name": "row_count_check",
                    "rule_type": "completeness_validation",
                    "field": "*",
                    "min_rows": 1,
                    "severity": "error",
                    "description": "Validate that dataset contains at least one row",
                },
                {
                    "rule_name": "duplicate_check",
                    "rule_type": "uniqueness_validation",
                    "field": "*",
                    "check_duplicates": True,
                    "severity": "warning",
                    "description": "Check for duplicate rows in the dataset",
                },
            ]
        )

        return quality_rules

    except Exception as e:
        logger.error(f"Error generating quality check rules: {e}")
        # Deliberate fallback: return no rules so quality-check creation continues with an
        # empty rule set rather than failing the pipeline step (P21 Req 6.4).
        return []


def create_quality_check_configuration(quality_rules: list[dict]) -> dict:
    """Create quality check configuration for Glue Data Quality.

    p30 R7.5: the ``execution_config`` block is REMOVED, not honoured. It
    persisted four keys — ``fail_on_error: True``, ``fail_on_warning: False``,
    ``max_error_threshold: 0.05``, ``max_warning_threshold: 0.20`` — and what
    they actually did was **nothing**. Each occurred exactly once in the
    repository, here at its point of write: no Lambda, shared module, container
    agent, PySpark template, CDK construct, dashboard component or test ever
    read one. They were carried into the ``first_run`` approval payload too, so
    they were inert *and* never rendered.

    They were not merely unused, they were misleading: ``fail_on_error: True``
    reads as "a quality failure fails this pipeline", and nothing in the system
    behaves that way. ``job_completion`` closes a run on Glue job state alone
    and contains no reference to quality at all; the one template that
    evaluates DQ wraps it in ``except Exception`` and reports success either
    way. Honouring them would mean building enforcement that does not exist,
    which is a behaviour change well outside a recording task — so R7.5's
    other branch is taken. The honest replacement is the ``quality_verdict``
    record on the state row (R7.2), which states what the generated code
    actually does, including ``blocks_run: False``.

    ``output_config`` is left as it stands: R7.5 does not name it, and it makes
    a weaker claim (a report IS generated and stored, by the inline block or
    the on-demand agent). Recorded here because it has no readers either, so a
    later task can retire it on the same evidence.
    """
    try:
        # Group rules by severity
        error_rules = [r for r in quality_rules if r.get("severity") == "error"]
        warning_rules = [r for r in quality_rules if r.get("severity") == "warning"]

        configuration = {
            "quality_rules": quality_rules,
            "rule_summary": {
                "total_rules": len(quality_rules),
                "error_rules": len(error_rules),
                "warning_rules": len(warning_rules),
            },
            "output_config": {"generate_report": True, "store_results": True, "notification_on_failure": True},
        }

        return configuration

    except Exception as e:
        logger.error(f"Error creating quality check configuration: {e}")
        return {"quality_rules": [], "error": str(e)}


def combine_infrastructure_and_quality_approval_data(
    run_id: str, quality_config: dict, quality_verdict: dict | None = None
) -> dict:
    """Combine infrastructure status and quality check configuration for first run approval.

    ``quality_verdict`` (p30 R7.2) travels with this payload because this is the
    moment a human is asked to approve a pipeline's first run while being shown
    a rule count — and for four of five (source_type, target_type) combinations
    those rules gate nothing. The verdict says which case the approver is in.
    """
    try:
        # Get infrastructure status from previous step — direct base table lookup
        infra_response = pipeline_runs_table.get_item(
            Key={"run_id": run_id, "step_name": StepName.CREATE_INFRASTRUCTURE}
        )

        infrastructure_status = {}
        if "Item" in infra_response:
            infra_item = infra_response["Item"]
            infrastructure_status = infra_item.get("output_data", {}).get("infrastructure_status", {})

        # Create combined approval payload
        combined_payload = {
            "approval_type": "first_run",
            "infrastructure_status": infrastructure_status,
            "quality_check_configuration": quality_config,
            "quality_verdict": quality_verdict or {},
            "combined_assessment": {
                "infrastructure_ready": infrastructure_status.get("overall_status") == "success",
                "quality_checks_configured": len(quality_config.get("quality_rules", [])) > 0,
                "estimated_monthly_cost": infrastructure_status.get("estimated_monthly_cost", 0),
                "total_quality_rules": quality_config.get("rule_summary", {}).get("total_rules", 0),
                "error_rules_count": quality_config.get("rule_summary", {}).get("error_rules", 0),
            },
            "pre_run_validation": {
                "infrastructure_checks": [
                    "RDS instances are available",
                    "S3 buckets are accessible",
                    "IAM roles have correct permissions",
                    "Glue resources are created",
                ],
                "quality_checks": [
                    f"{quality_config.get('rule_summary', {}).get('total_rules', 0)} quality rules configured",
                    "Data type validations enabled",
                    "Null value checks configured",
                    "Completeness validation active",
                ],
            },
            "risk_summary": {
                "cost_risk": "high" if infrastructure_status.get("estimated_monthly_cost", 0) > 100 else "medium",
                "data_quality_risk": "low"
                if quality_config.get("rule_summary", {}).get("error_rules", 0) > 0
                else "medium",
                "overall_risk": "medium",
            },
        }

        return combined_payload

    except Exception as e:
        logger.error(f"Error combining approval data: {e}")
        return {
            "approval_type": "first_run",
            "quality_check_configuration": quality_config,
            # Carried on the degraded payload too: the verdict is derived
            # independently of the infrastructure read that failed here, and an
            # approver seeing a partial payload still needs to know whether
            # anything gates the write.
            "quality_verdict": quality_verdict or {},
            "error": f"Failed to combine approval data: {e!s}",
        }


@step_handler("create_quality_checks")
def lambda_handler(event, context):
    """
    Lambda function to add data quality validation rules to the pipeline.

    Args:
        event: Lambda event containing pipeline configuration and quality requirements
        context: Lambda context object

    Returns:
        dict: Configured quality check rules
    """
    # p39 R6.1: stage-duration anchor, bound BEFORE the `try` so the failure path
    # can report a duration even for an exception raised on the first statement.
    # `time` is imported handler-locally so it resolves from sys.modules at call
    # time, matching the sibling step Lambdas (create_code:392-398).
    import time as _time

    _metrics_start = _time.time()
    try:
        logger.info(f"Quality checks creation event: {json.dumps(event)}")

        # Extract required data from event
        run_id = event.get("run_id")
        pipeline_id = event.get("pipeline_id")
        mapping_id = event.get("mapping_id")

        if not run_id or not pipeline_id:
            raise ValueError("run_id and pipeline_id are required")

        logger.append_keys(run_id=run_id, pipeline_id=pipeline_id, step_name=StepName.CREATE_QUALITY_CHECKS)

        # Get target schema for quality check generation
        target_schema = get_target_schema_for_quality_checks(mapping_id) if mapping_id else {}

        # Generate quality check rules based on target schema
        logger.info(f"Generating quality checks for pipeline: {pipeline_id}")
        quality_rules = generate_quality_check_rules(target_schema)

        # Create quality check configuration
        quality_config = create_quality_check_configuration(quality_rules)

        # p30 R7.2: Quality_Verdict mode for this run's generated code. Derived
        # from the create_code row's rendered template + generated DQDL, NOT
        # from quality_rules above — those are a different rule vocabulary and
        # are non-empty even when the job carries no DQ at all.
        code_facts = get_code_generation_facts(run_id)
        quality_verdict = derive_quality_verdict(
            template_used=code_facts.get("template_used"),
            dqdl_rules=code_facts.get("dqdl_rules"),
            target_type=code_facts.get("target_type"),
            determined_from=code_facts["determined_from"],
            # p64 R6.6. `.get` rather than `[...]`: the two error arms above return
            # a dict holding only `determined_from`, and on those arms the mode is
            # advisory regardless, so an absent key is correct rather than a KeyError.
            data_quality_enabled=code_facts.get("data_quality_enabled"),
        )
        logger.info(
            f"Quality verdict mode for {run_id}: {quality_verdict['mode']} "
            f"(template={quality_verdict['template_used'] or 'unknown'}, "
            f"dqdl_rules={quality_verdict['dqdl_rule_count']}, "
            f"dq_enabled={quality_verdict['data_quality_enabled']})"
        )

        # Generate timestamps
        timestamp = datetime.now(UTC).isoformat()

        # Create combined approval payload (infrastructure + quality checks)
        approval_payload = combine_infrastructure_and_quality_approval_data(run_id, quality_config, quality_verdict)

        # Store quality checks creation result in pipeline runs table
        # Convert floats to Decimal for DynamoDB compatibility
        pipeline_runs_table.put_item(
            Item=convert_floats_to_decimal(
                {
                    "run_id": run_id,  # Partition key
                    # P28 R8.2 (task 14.2): canonical step name — the legacy
                    # "CreateQualityChecks" state-row variant is retired.
                    "step_name": StepName.CREATE_QUALITY_CHECKS,
                    "status": "success",
                    "step_sequence": STEP_SEQUENCE[StepName.CREATE_QUALITY_CHECKS],
                    "timestamp": timestamp,
                    "pipeline_id": pipeline_id,  # For PipelineIndex GSI
                    "original_pipeline_id": pipeline_id,
                    "approval_required": True,  # Always require approval for first run after infrastructure + quality setup
                    "output_data": {
                        "quality_configuration": quality_config,
                        "total_rules": len(quality_rules),
                        "error_rules": len([r for r in quality_rules if r.get("severity") == "error"]),
                        "warning_rules": len([r for r in quality_rules if r.get("severity") == "warning"]),
                        # p30 R7.2: inside output_data rather than at the row's
                        # top level, because output_data is what the run-detail
                        # API returns verbatim per step (handlers/
                        # pipelines_runs.py builds step_info with
                        # "output_data": item_dict(item, "output_data")) —
                        # top-level attributes are dropped unless explicitly
                        # listed there. The approval_handler's first_run reader
                        # reads it from here for the same reason.
                        "quality_verdict": quality_verdict,
                        "approval": approval_payload,  # Native dict, not JSON string
                    },
                }
            )
        )
        logger.info(f"Quality checks creation state stored in {PIPELINE_RUNS_TABLE}")

        # Publish stage metrics (p39 R6.1) — RECORDING ONLY. This emits a duration
        # and a success/failure count; it evaluates no threshold and gates nothing.
        # That boundary is `LGR-eee8ac8-6` (template / ratified), the record that
        # deleted this step's inert `fail_on_error` / `max_error_threshold` keys
        # rather than honour them, "because honouring them would mean building
        # enforcement, which is outside a recording change" — see
        # `create_quality_check_configuration`'s docstring. Nothing here reintroduces
        # one.
        #
        # No flush is needed on this path and none is added: `addObservability`
        # sets `POWERTOOLS_ENABLED='true'` on this Lambda
        # (`compute-stack.ts:887`, applied at `:902`), so `put_metric` takes the
        # EMF branch. `record_stage_execution`'s own `flush()` is a no-op there.
        if PipelineMetrics is not None:
            try:
                _duration_ms = (_time.time() - _metrics_start) * 1000
                PipelineMetrics.record_stage_execution(
                    stage_name="CreateQualityChecks",
                    pipeline_id=pipeline_id or "unknown",
                    status="completed",
                    duration_ms=_duration_ms,
                )
            except Exception:
                # p39 R6.5 / requirements constraint 8: log, never fail the step. A
                # stage-duration emission is telemetry; losing it must not turn a
                # successful quality-check creation into a failed one. What is NOT
                # acceptable is losing it with no trace — the `except Exception: pass`
                # shape this deliberately avoids (commit 8f3f9e1b30, "Replace 7 bare
                # except clauses with specific types + logging", history rather than a
                # ratified decision). The nearest ratified statement of the same stance
                # is `LGR-9e76249-4` (template / ratified): this pipeline's checks
                # record their findings and never fail the step. `exc_info` is what
                # makes a recurrence diagnosable.
                logger.warning(
                    "Failed to record CreateQualityChecks stage metrics for pipeline=%s (success path)",
                    pipeline_id or "unknown",
                    exc_info=True,
                )
        else:
            # p39 R6.6: an unreachable emit must not be indistinguishable from a
            # working one. If the Lambda layer ever loses `metrics_facade`, the import
            # guard above silences both emits — this line is the only signal that the
            # absent series has that cause rather than "the stage never ran".
            logger.warning(
                "PipelineMetrics is unavailable (metrics_facade did not import), so no CreateQualityChecks "
                "stage duration was recorded for pipeline=%s (success path)",
                pipeline_id or "unknown",
            )

        # Return output per spec (convert floats for consistency)
        return convert_floats_to_decimal(
            {
                "statusCode": 200,
                "run_id": run_id,
                "pipeline_id": pipeline_id,
                "quality_configuration": quality_config,
                "total_rules": len(quality_rules),
                "error_rules": len([r for r in quality_rules if r.get("severity") == "error"]),
                "warning_rules": len([r for r in quality_rules if r.get("severity") == "warning"]),
                "quality_verdict": quality_verdict,
                "approval_required": True,
                "next_step": "first_run_approval",
            }
        )

    except Exception as e:
        error_message = f"Error in quality checks creation: {e!s}"
        logger.error(error_message)

        # p39 R6.1: the failure path emits too, so a stage that ran and failed is
        # distinguishable from a stage that never ran. Recording only — see the
        # success path above for the `LGR-eee8ac8-6` boundary.
        if PipelineMetrics is not None:
            try:
                _duration_ms = (_time.time() - _metrics_start) * 1000
                PipelineMetrics.record_stage_execution(
                    stage_name="CreateQualityChecks",
                    pipeline_id=event.get("pipeline_id") or "unknown",
                    status="failed",
                    duration_ms=_duration_ms,
                )
            except Exception:
                # p39 R6.5 / requirements constraint 8: log, never fail the step — and
                # on this path especially, never displace the real failure. The handler
                # is already unwinding an exception it logged one line above and will
                # re-raise as a StepFailure below; a metrics problem must not become
                # the error the run is recorded under.
                logger.warning(
                    "Failed to record CreateQualityChecks stage metrics for pipeline=%s (failure path)",
                    event.get("pipeline_id") or "unknown",
                    exc_info=True,
                )
        else:
            # p39 R6.6, same reasoning as the success path above.
            logger.warning(
                "PipelineMetrics is unavailable (metrics_facade did not import), so no CreateQualityChecks "
                "stage duration was recorded for pipeline=%s (failure path)",
                event.get("pipeline_id") or "unknown",
            )

        # Write error to pipeline runs table
        try:
            run_id = event.get("run_id", "unknown")
            pipeline_runs_table.put_item(
                Item=convert_floats_to_decimal(
                    {
                        "run_id": run_id,  # Partition key
                        "step_name": StepName.CREATE_QUALITY_CHECKS,
                        "status": "failed",
                        "step_sequence": STEP_SEQUENCE[StepName.CREATE_QUALITY_CHECKS],
                        "timestamp": datetime.now(UTC).isoformat(),
                        "pipeline_id": event.get("pipeline_id", "unknown"),  # For PipelineIndex GSI
                        "original_pipeline_id": event.get("pipeline_id", "unknown"),
                        "error_message": error_message,
                        "error_type": "QualityChecksError",
                    }
                )
            )
        except Exception as db_error:
            logger.error(f"Failed to write error to DynamoDB: {db_error!s}")

        # P28 R1.1: raise so the Step Functions task fails and Retry/Catch fire
        # (an error payload return would be treated as task success).
        raise StepFailure(
            "create_quality_checks",
            error_message,
            details={
                "run_id": event.get("run_id", "unknown"),
                "pipeline_id": event.get("pipeline_id", "unknown"),
            },
        ) from e
