def _stored_item(**kwargs) -> dict[str, Any]:
    with patch.object(_mod, "mappings_table") as mock_table:
        mock_table.get_item.return_value = {}
        _mod.store_mapping_separately(
            "mapping-hash-abc",
            _ai_body(),
            "src-hash",
            "tgt-hash",
            RUN_ID,
            "us.anthropic.claude-sonnet-4-6",
            False,
            **kwargs,
        )
    return dict(mock_table.put_item.call_args.kwargs["Item"])


def test_the_written_item_carries_the_pipeline_id():
    item = _stored_item(pipeline_id=PIPELINE_ID)

    assert item["pipeline_id"] == PIPELINE_ID
    # Beside, not instead of — `run_id` keeps its meaning.
    assert item["run_id"] == RUN_ID


def test_pipeline_id_is_absent_rather_than_empty_when_not_supplied():
    """Absent, not `""` — the same rule `run_id` follows one line above it.

    An empty string is a record naming a pipeline called "", which a correlating
    reader cannot tell from a real one.
    """
    assert "pipeline_id" not in _stored_item()
    assert "pipeline_id" not in _stored_item(pipeline_id="")
    assert "pipeline_id" not in _stored_item(pipeline_id=None)


#: Attributes whose value is the wall clock at write time, so two writes of the
#: same content legitimately differ on them.
_VOLATILE_ATTRIBUTES = frozenset({"created_timestamp", "updated_timestamp"})


def test_adding_pipeline_id_left_every_other_attribute_alone():
    """The attribute is additive; the record's existing shape is unchanged."""
    without = _stored_item()
    with_id = _stored_item(pipeline_id=PIPELINE_ID)

    assert set(with_id) - set(without) == {"pipeline_id"}
    ignored = _VOLATILE_ATTRIBUTES | {"pipeline_id"}
    assert {k: v for k, v in with_id.items() if k not in ignored} == {
        k: v for k, v in without.items() if k not in ignored
    }
    # The volatile pair is still written on both paths — ignored, not dropped.
    assert set(without) >= _VOLATILE_ATTRIBUTES
    assert set(with_id) >= _VOLATILE_ATTRIBUTES


def test_pipeline_id_is_a_trailing_keyword_so_positional_callers_are_unmoved():
    """The six pre-existing parameters keep their positions.

    The production call site passes them positionally, so inserting `pipeline_id`
    earlier would silently shift `run_id`, `ai_model_used` and `update_existing`.
    """
    params = list(inspect.signature(_mod.store_mapping_separately).parameters)
    assert params == [
        "mapping_id",
        "mapping_result",
        "source_schema_hash",
        "target_schema_hash",
        "run_id",
        "ai_model_used",
        "update_existing",
        "pipeline_id",
    ]


def test_the_production_call_site_actually_passes_a_pipeline_id():
    """The wiring, asserted over the parsed source rather than over its text.

    A test of `store_mapping_separately` alone would pass with the call site
    still omitting the argument, which is the whole defect. Read by AST because
    matching source text is what `LGR-b46a5bb-4` records as the wrong tool for
    this — the module's own comments name the function.
    """
    with open(os.path.join(_schema_mapping_dir, "lambda_function.py"), encoding="utf-8") as handle:
        tree = ast.parse(handle.read())

    calls = [
        node
        for node in ast.walk(tree)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "store_mapping_separately"
    ]
    assert len(calls) == 1, "expected exactly one production call site"
    keywords = {kw.arg for kw in calls[0].keywords}
    assert "pipeline_id" in keywords
