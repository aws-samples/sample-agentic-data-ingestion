def _ai_body():
    return {
        "mappings": [{"target_field": "name", "source_field": "name", "confidence": 0.97}],
        "unmapped_source_fields": [],
        "unmapped_target_fields": [],
        "mapping_summary": "ai mapping",
    }


class _TemperatureRefusingBedrock:
    """A `bedrock-runtime` stand-in shaped like the live model.

    Refuses any Converse call carrying `temperature` with a botocore-shaped
    `ValidationException`, and answers normally once it is gone.
    """

    def __init__(self) -> None:
        self.calls: list[dict[str, Any]] = []

    def converse(self, **kwargs: Any) -> dict[str, Any]:
        self.calls.append(kwargs)
        if "temperature" in kwargs.get("inferenceConfig", {}):
            exc = Exception(_OBSERVED_REJECTION)
            exc.response = {"Error": {"Code": "ValidationException", "Message": _OBSERVED_REJECTION}}
            raise exc
        return {
            "output": {"message": {"content": [{"text": json.dumps(_ai_body())}]}},
            "usage": {"inputTokens": 10, "outputTokens": 20},
        }


# --- Fix 1: the live rejection no longer degrades the mapping ---------


def test_temperature_rejection_no_longer_falls_back_to_substring_matching():
    """The observed failure now produces an AI mapping with honest provenance."""
    fake = _TemperatureRefusingBedrock()

    with patch.object(_mod, "bedrock_runtime", fake):
        result = _mod.generate_mapping_with_bedrock(
            _source_schema(), _target_schema(), "", "us.anthropic.claude-sonnet-5"
        )

    assert result["generated_by"] == "us.anthropic.claude-sonnet-5"
    assert result["generated_by"] != _mod.FALLBACK_GENERATED_BY
    assert not result.get("requires_manual_approval")
    # Two wire calls: the refused one and the retry without `temperature`.
    assert len(fake.calls) == 2
    assert "temperature" in fake.calls[0]["inferenceConfig"]
    assert "temperature" not in fake.calls[1]["inferenceConfig"]


def test_a_temperature_accepting_model_still_receives_temperature():
    """The determinism default is not discarded for every model to fix one."""
    with patch.object(_mod, "bedrock_runtime") as mock_bedrock:
        mock_bedrock.converse.return_value = {
            "output": {"message": {"content": [{"text": json.dumps(_ai_body())}]}},
            "usage": {"inputTokens": 10, "outputTokens": 20},
        }
        _mod.generate_mapping_with_bedrock(_source_schema(), _target_schema(), "", "us.anthropic.claude-sonnet-4-6")

    mock_bedrock.converse.assert_called_once()
    config = mock_bedrock.converse.call_args.kwargs["inferenceConfig"]
    assert config["temperature"] == model_config.DEFAULT_TEMPERATURE
    assert config["maxTokens"] == model_config.DEFAULT_MAX_TOKENS


def test_an_unrecoverable_bedrock_failure_still_falls_back_and_says_so_loudly():
    """The fallback contract is intact, and the degradation is no longer quiet.

    P28 R3.1's provenance stamping is what makes a Bedrock outage survivable, so
    this path must stay reachable. What changed is that it now states the
    consequence — the previous one-line `logger.error` said only that a call
    failed, and the incident was found through a UI label instead.
    """
    with patch.object(_mod, "bedrock_runtime") as mock_bedrock, patch.object(_mod, "logger") as mock_logger:
        mock_bedrock.converse.side_effect = Exception("bedrock unavailable")
        result = _mod.generate_mapping_with_bedrock(_source_schema(), _target_schema(), "", "us.test-model")

    assert result["generated_by"] == _mod.FALLBACK_GENERATED_BY
    assert result["requires_manual_approval"] is True
    logged = " ".join(str(call) for call in mock_logger.exception.call_args_list)
    assert "DEGRADED MAPPING" in logged
    assert "us.test-model" in logged


def test_the_loud_log_survives_a_failure_before_the_model_id_is_resolved():
    """The handler names `model_id`, not `selected_model`.

    `selected_model` is bound at `lambda_function.py:1135`, inside the same
    `try`, so naming it in the handler would raise `NameError` for any earlier
    failure and turn a degraded mapping into a failed step. The sample-values
    render at `:1092` is one such earlier point, so a raise from there reaches
    the handler with `selected_model` unbound and the schemas still usable.
    """
    with (
        patch.object(_mod, "render_sample_values_section", side_effect=Exception("boom")),
        patch.object(_mod, "logger") as mock_logger,
    ):
        result = _mod.generate_mapping_with_bedrock(_source_schema(), _target_schema(), "", "us.test-model")

    # No NameError escaped: the fallback ran and the log names the model.
    assert result["generated_by"] == _mod.FALLBACK_GENERATED_BY
    logged = " ".join(str(call) for call in mock_logger.exception.call_args_list)
    assert "DEGRADED MAPPING" in logged
    assert "us.test-model" in logged


