# These are *preservation* pins over a path that works, so **current
# converter output IS the oracle**: every `code` below was transcribed from
# `convert()` as it runs today, byte-exactly, by running it against the
# working tree. The Spark-derived rule that governs p40's *defect* tests —
# `test_literal_receiver_cast.py`,
