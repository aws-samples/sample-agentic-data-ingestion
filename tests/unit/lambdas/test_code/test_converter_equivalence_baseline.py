BUG_SHAPES_1_7_TO_1_10 = {
    "1.7": 'df_transformed = df.withColumn("a", trim(col("x"))).withColumn("b", lower(col("y")))',
    "1.8": 'df_transformed = df.withColumn("state", when(col("state") == "CA", "California").otherwise(col("state")))',
    "1.9": (
        'df_transformed = df.withColumn("s", when(col("s") == "CA", "CA_full")'
        '.when(col("s") == "NY", "NY_full").otherwise("Other"))'
    ),
    "1.10": 'df_transformed = df.withColumn("a", trim(col("x"))).select("a")',
}


def _method_chain(node: ast.AST) -> list[str]:
    """Method names along one call chain, outermost first.

    ``df.withColumn(...).select(...)`` yields ``["select", "withColumn"]``.
    Stops at the chain's root, so an inner call's chain is a suffix of its
    enclosing call's chain — which means checking every ``Call`` in a tree is
    equivalent to checking each chain once.
    """
    names: list[str] = []
    current = node
    while isinstance(current, ast.Call) and isinstance(current.func, ast.Attribute):
        names.append(current.func.attr)
        current = current.func.value
    return names


def _called_name(node: ast.AST) -> "str | None":
    """The callee name of *node* if it is a call, whether plain or a method."""
    if not isinstance(node, ast.Call):
        return None
    if isinstance(node.func, ast.Name):
        return node.func.id
    if isinstance(node.func, ast.Attribute):
        return node.func.attr
    return None


def is_bug_condition_d3(source: str) -> bool:
    """`bugfix.md` isBugCondition_D3 — does *source* contain one of 1.7-1.10?

    True when any statement has ≥2 chained ``.withColumn``, an
    ``otherwise(<non-literal>)``, ≥2 ``when`` calls in one expression, or
    ``.withColumn`` chained with ``.select``.

    A block that is not parseable Python returns False: it cannot be one of the
    four shapes, all of which are single valid statements. `SyntaxError` is
    caught by name — `LGR-8f3f9e1-1` (backfilled) removed bare `except`
    repo-wide and the AST converter must not reintroduce one.

    `SyntaxWarning` is suppressed because real generated PySpark carries regex
    literals in plain strings (`rlike("@example\\.com$")`), and an
    invalid-escape warning from parsing the model's text is not a finding about
    the converter.
    """
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            tree = ast.parse(source)
    except SyntaxError:
        return False

    for statement in tree.body:
        when_calls = 0
        for node in ast.walk(statement):
            if _called_name(node) == "when":
                when_calls += 1
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                if node.func.attr == "otherwise" and node.args and not isinstance(node.args[0], ast.Constant):
                    return True  # 1.8 — otherwise(<non-literal>)
                chain = _method_chain(node)
                if chain.count("withColumn") >= 2:
                    return True  # 1.7 — ≥2 chained .withColumn
                if "withColumn" in chain and "select" in chain:
                    return True  # 1.10 — .withColumn chained with .select
        if when_calls >= 2:
            return True  # 1.9 — ≥2 chained .when
    return False


