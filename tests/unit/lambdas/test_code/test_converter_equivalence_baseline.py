class TestP40UnpinnedCastTargetKeys:
    """`F(X) = F'(X)` for the 8 `_CAST_TARGETS` keys nothing pinned (1.15).

    Preservation pins, on a `col(...)` receiver, for the half of the cast
    table `CONVERSION_BASELINE` never reached. They exist so that p40's edit
    inside `_cast` (tasks 4.2 and 5.1) has preservation evidence over the
    whole table rather than half of it — which is why R8 puts them before the
    edit, not after.

    Green on the first run, by definition: the expectations were transcribed
    from today's output. A red here is a transcription error to investigate,
    never an expectation to adjust.

    **Validates: Requirements R8, R9**
    """

    @pytest.mark.parametrize("case", _cases(P40_UNPINNED_CAST_KEY_PINS))
    def test_emitted_code_is_byte_identical_to_the_captured_baseline(self, case: BaselineCase):
        assert PySpark2PandasConverter.convert(case.source)["code"] == case.code

    @pytest.mark.parametrize("case", _cases(P40_UNPINNED_CAST_KEY_PINS))
    def test_conversion_report_is_identical_to_the_captured_baseline(self, case: BaselineCase):
        """The report is part of the public surface (3.9), so a cast whose
        emission is preserved but whose reported constructs are not is still a
        regression."""
        report = PySpark2PandasConverter.convert(case.source)["conversion_report"]
        assert report == {
            "input_lines": case.input_lines,
            "output_lines": case.output_lines,
            "constructs_converted": case.constructs,
        }

    def test_the_pins_cover_exactly_the_eight_keys_bugfix_1_15_found_unpinned(self):
        """A pin table that drifted off 1.15's list would leave a key
        uncovered while looking complete. The keys are read from
        `_CAST_TARGETS` itself, so a key renamed in the converter fails here
        rather than silently dropping out of coverage."""
        # Imported function-locally so this whole section stays additive —
        # the module's import block at the top is left untouched.
        from pyspark_to_pandas import _CAST_TARGETS

        assert set(P40_PIN_CAST_KEY.values()) == set(P40_UNPINNED_CAST_TARGET_KEYS)
        assert set(_CAST_TARGETS).issuperset(P40_UNPINNED_CAST_TARGET_KEYS)
        assert {case.case_id for case in P40_UNPINNED_CAST_KEY_PINS} == set(P40_PIN_CAST_KEY)
        for case in P40_UNPINNED_CAST_KEY_PINS:
            assert P40_PIN_CAST_KEY[case.case_id] in case.source, (
                f"{case.case_id} does not exercise the key it claims: {P40_PIN_CAST_KEY[case.case_id]}"
            )

    def test_no_pinned_key_is_a_string_key_so_task_5_1_cannot_move_these_pins(self):
        """What makes these pins evidence rather than ceremony. p40 task 5.1
        rewrites `_CAST_TARGETS["string"]` and `["StringType"]` only (R7,
        `design.md` §4.3); none of the eight keys here is one of those, so
        5.1 must leave every expectation above byte-identical. If a pin has
        to be amended when 5.1 lands, 5.1 touched more of the table than it
        was supposed to."""
        assert P40_UNPINNED_CAST_TARGET_KEYS.isdisjoint({"string", "StringType"})

    def test_the_pins_do_not_collide_with_or_duplicate_the_p32_tables(self):
        """The two integrity properties `TestOracleIntegrity` gives the p32
        tables, held for this table too: ids are unique and disjoint from
        `ALL_CASES` (a duplicate id would silently drop a pinned input), and
        no pin is one of the `bugfix.md`-1.7-to-1.10 shapes whose current
        output is the defect."""
        ids = [case.case_id for case in P40_UNPINNED_CAST_KEY_PINS]
        assert sorted(ids) == sorted(set(ids))
        assert set(ids).isdisjoint({case.case_id for case in ALL_CASES})
