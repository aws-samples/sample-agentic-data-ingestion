def test_an_xlsx_upload_reaches_the_excel_branch_and_records_its_canonical_format(schema_extract, monkeypatch):
    """R6.3: the dispatch selects the Excel branch and the run records that format.

    Driven through ``lambda_handler`` rather than by calling the extractor,
    because R6.3 is a claim about the **dispatch**: the value ``file_validation``
    derives from the ``xlsx`` extension has to be the value this chain of
    ``elif``s selects the Excel branch on, and the value the run then reports.
    Calling ``extract_schema_from_excel`` directly would prove the extractor
    works and prove nothing about routing.

    The extractor and the converter are the real ones over the real committed
    workbook, so "reached the branch" is evidenced by the branch's own two
    outputs — the Worksheet's schema and the converted object — rather than by a
    stub's call record.
    """
    lf, mock_s3, mock_table = schema_extract
    gen = _load_fixture_declaration()
    key = f"uploads/{gen.EXCEL_FIXTURE}"
    canonical = _canonical_format_for_xlsx(key)

    monkeypatch.delenv("PROCESSED_BUCKET", raising=False)
    _seed_previous_state(mock_table, key)
    _serve(mock_s3, _committed_fixture_bytes(gen.EXCEL_FIXTURE))

    # The defensive `else` also calls extract_schema_from_json, so its absence
    # from the call record is the evidence that the fallthrough was not the route
    # taken — the same negative the p46 routing tests turn on.
    json_reader = MagicMock(return_value={"type": "object", "properties": {"WRONG": {"type": "string"}}})
    logger_stub = MagicMock()
    # p55 task 5.1: the pipeline carries a Selected_Worksheet, because this
    # fixture is multi-sheet and a multi-sheet workbook with no selection now
    # refuses. See :func:`_pipeline_record_selecting`.
    pipeline_read = MagicMock(return_value=_pipeline_record_selecting(gen.EXCEL_ACTIVE_SHEET))
    with patch.multiple(
        lf, extract_schema_from_json=json_reader, logger=logger_stub, get_pipeline_metadata=pipeline_read
    ):
        result = lf.lambda_handler(_event(canonical), None)

    assert json_reader.called is False, "the JSON reader ran, so the dispatch did not take the Excel branch"
    assert [str(call) for call in logger_stub.warning.call_args_list if "Unhandled source_format" in str(call)] == [], (
        "the Canonical_Format for xlsx reached the defensive else branch"
    )

    # R6.3 proper: the recorded source_format is the Canonical_Format associated
    # with `xlsx`, compared against the value derived from FORMAT_MAP.
    assert result["statusCode"] == 200
    assert result["source_format"] == canonical

    # The schema is the ACTIVE Worksheet's columns — the branch read the workbook
    # this test served, not a stub and not the second sheet.
    assert result["extracted_schema"] == gen.EXPECTED_EXCEL_JSON_SCHEMA
    for absent in gen.EXCEL_SECOND_SHEET_COLUMNS:
        assert absent not in result["extracted_schema"]["properties"], (
            f"{absent!r} comes from Worksheet {gen.EXCEL_SECOND_SHEET!r}; the active sheet "
            f"{gen.EXCEL_ACTIVE_SHEET!r} was not the one described"
        )

    # The branch's other half ran too: the object the Glue job will read is the
    # converted CSV, and the pair naming it is present on this arm
    # (`LGR-5c539a6-2` requires it on both).
    converted_uri = f"s3://{PROCESSED_BUCKET}/converted/{PIPELINE_ID}/{RUN_ID}/source.csv"
    assert result["readable_source_uri"] == converted_uri
    assert result["readable_source_format"] == lf._EXCEL_READABLE_FORMAT
    assert result["json_s3_uri"] == f"s3://{SOURCE_BUCKET}/{key}", "the canonical source URI was repointed"


