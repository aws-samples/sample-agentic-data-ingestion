def _load_fixture_declaration():
    """Load ``generate_binary_fixtures`` by path, per its module docstring.

    ``tests/fixtures/data/`` is not a package. The ``sys.modules`` registration
    before ``exec_module`` is the recipe that module documents and asks callers
    to keep — unnecessary today, required the moment anyone adds
    ``from __future__ import annotations`` there.
    """
    path = FIXTURE_DIR / "generate_binary_fixtures.py"
    spec = importlib.util.spec_from_file_location("generate_binary_fixtures", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _load_format_detection() -> dict[str, Any]:
    """``FORMAT_MAP`` and ``detect_format``, executed from ``file_validation``'s
    real source with **no import side effects** (``LGR-c58f276-4``).

    Same loader as ``tests/unit/shared/test_format_delimiters.py``'s. It is not a
    text match over source: the real nodes are compiled and the real function is
    called (``LGR-b46a5bb-4``).
    """
    tree = ast.parse(_FILE_VALIDATION_SOURCE.read_text())

    format_map_node: ast.Assign | None = None
    detect_format_node: ast.FunctionDef | None = None
    for node in ast.iter_child_nodes(tree):
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "FORMAT_MAP"
        ):
            format_map_node = node
        elif isinstance(node, ast.FunctionDef) and node.name == "detect_format":
            detect_format_node = node

    assert format_map_node is not None, "FORMAT_MAP is no longer a module-level assignment"
    assert detect_format_node is not None, "detect_format is no longer a module-level function"

    namespace: dict[str, Any] = {}
    module = ast.Module(body=[format_map_node, detect_format_node], type_ignores=[])
    exec(compile(ast.fix_missing_locations(module), str(_FILE_VALIDATION_SOURCE), "exec"), namespace)
    return {"FORMAT_MAP": namespace["FORMAT_MAP"], "detect_format": namespace["detect_format"]}


def _canonical_format_for_xlsx(key: str) -> str:
    """The Canonical_Format ``file_validation`` associates with ``xlsx``.

    Derived two ways from the same source and required to agree: the
    ``FORMAT_MAP`` entry, and ``detect_format`` executed over the real upload key
    this test then hands to ``schema_extract``. Agreement matters because it is
    the *travelled* value — what ``file_validation`` puts on its result — that
    the dispatch keys on, not the table entry in isolation.
    """
    loaded = _load_format_detection()
    detected = loaded["detect_format"](key)

    assert detected == loaded["FORMAT_MAP"]["xlsx"], (
        f"detect_format({key!r}) is {detected!r} but FORMAT_MAP['xlsx'] is {loaded['FORMAT_MAP']['xlsx']!r} — "
        f"the value that travels and the value in the table disagree"
    )
    assert detected != "unknown", "an xlsx key resolves to no Canonical_Format; F1/F2 in test_format_detection.py"
    return detected


